import { test, expect } from '@playwright/test';
import { bootstrap, control } from './session';
test('WEB-CON-READ lists, sections, scrubber, labeled card, safe actions, vCard and native updates', async ({page,context,request},info) => {
    await bootstrap(context,request);
    const fixture=await control(request,'/contacts-read');
    await page.goto('/messages');
    await page.getByRole('button',{name:'Switch app',exact:true}).click();
    await page.getByRole('button',{name:'Contacts',exact:true}).click();
    const compact=info.project.use.viewport!.width<1024;
    if(compact)await page.getByRole('button',{name:/All Contacts/}).click();
    await expect(page.getByRole('heading',{name:'All Contacts',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:/Zoe M Adler/}).first()).toBeVisible();
    const lists=page.getByRole('navigation',{name:'Contact lists'});
    if(compact)await page.getByRole('button',{name:'Back to lists',exact:true}).click();
    await lists.getByRole('button',{name:'Bridge Test Account',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Bridge Test Account',exact:true})).toBeVisible();
    await expect(page.locator('.contact-row')).toHaveCount(2);
    if(compact)await page.getByRole('button',{name:'Back to lists',exact:true}).click();
    await lists.getByRole('button',{name:/Bridge Test Friends/}).click();
    await expect(page.getByRole('heading',{name:'Bridge Test Friends',exact:true})).toBeVisible();
    await expect(page.locator('.contact-my-card')).toContainText('My Card');
    await expect(page.locator('.contact-my-card .avatar img')).toHaveJSProperty('complete',true);
    await page.getByRole('button',{name:'Jump to Z',exact:true}).click();
    await expect(page.locator('.contact-row',{hasText:'Amy Zulu'})).toBeVisible();
    await page.getByRole('button',{name:'Jump to #',exact:true}).click();
    await expect(page.locator('.contact-row',{hasText:'123 Test Studio'})).toBeVisible();
    await page.getByLabel('Sort by',{exact:true}).selectOption('given');
    await page.getByLabel('Display order',{exact:true}).selectOption('family');
    await expect(page.locator('.contact-my-card')).toContainText('Adler Zoe M');
    await page.reload();
    await expect(page.getByLabel('Sort by',{exact:true})).toHaveValue('given');
    await expect(page.getByLabel('Display order',{exact:true})).toHaveValue('family');
    const search=page.getByRole('searchbox',{name:'Search Contacts',exact:true});
    await search.fill('Test City');
    await expect(page.locator('.contact-row')).toHaveCount(1);
    await expect(page.locator('.contact-row')).toContainText('Adler Zoe M');
    await page.locator('.contact-row').click();
    const card=page.getByRole('article',{name:'Adler Zoe M'});
    await expect(card).toBeVisible();
    await expect(card.getByRole('heading',{name:'Adler Zoe M',exact:true})).toBeVisible();
    await expect(card.getByRole('link',{name:'call',exact:true})).toHaveAttribute('href','tel:%2B15555550123');
    await expect(card.getByRole('link',{name:'mail',exact:true})).toHaveAttribute('href','mailto:contacts-read%40example.com');
    await expect(card.getByRole('link',{name:'video',exact:true})).toHaveAttribute('href','facetime:%2B15555550123');
    await expect(card.locator('dt')).toContainText(['Mobile','work','home','unsafe','work','friend','work','work','birthday','anniversary']);
    await expect(card).toContainText('Example Friend');
    await expect(card.getByRole('link',{name:'javascript:alert(1)',exact:true})).toHaveCount(0);
    await expect(card).not.toContainText('hidden sensitive note');
    await expect(card.getByRole('link',{name:/1 Example Street/})).toHaveAttribute('href',/^https:\/\/maps.apple.com\//);
    const download=page.waitForEvent('download');
    await card.getByRole('button',{name:'Export vCard',exact:true}).click();
    const exported=await download;
    const stream=await exported.createReadStream();let bytes='';for await(const part of stream!)bytes+=part.toString();
    expect(bytes).toContain('FN:Adler Zoe M');expect(bytes).toContain('EMAIL:contacts-read@example.com');expect(bytes).toContain('X-ABLabel:Mobile');expect(bytes).not.toContain('hidden sensitive note');
    await control(request,'/contacts-read?update=1');
    await expect(page.getByRole('article',{name:'Adler Zoe Updated M'})).toBeVisible();
    await page.getByRole('button',{name:'Back to contacts',exact:true}).click();
    await search.fill('does-not-exist');await expect(page.getByRole('status')).toContainText('No results');
    await search.fill('contacts-read@example.com');await page.locator('.contact-row').click();
    await page.getByRole('navigation',{name:'Quick actions'}).getByRole('button',{name:'message',exact:true}).click();
    await expect(page).toHaveURL(/\/messages\/new\?to=/);
    await expect(page.locator('.recipient-tokens')).toContainText('+15555550123');
});
