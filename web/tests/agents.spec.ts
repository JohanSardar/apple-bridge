import { test, expect, type Page } from '@playwright/test';
import { createHash, randomBytes, randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { control } from './session';
async function virtualKey(page: Page) {
    const cdp = await page.context().newCDPSession(page);
    await cdp.send('WebAuthn.enable');
    await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
}
test('WEB-AGENT-OAUTH connector consent, access levels, approval screens and token rotation', async ({ page, request }, info) => {
    await virtualKey(page);
    const { url } = await control(request, '/enroll');
    await page.goto(url);
    await page.getByRole('button', { name: 'Continue', exact: true }).click();
    await expect(page.getByText('No Messages', { exact: true })).toBeVisible();
    const origin = new URL(process.env.AB_WEB_URL!).origin;
    const ownerHeaders = { Origin: origin };
    const evidence = '../lab/evidence/private/web';
    await mkdir(evidence, { recursive: true });
    const clientResponse = await request.post('/oauth/register', { data: { client_name: 'Research assistant', redirect_uris: ['https://connector.example/callback'], token_endpoint_auth_method: 'none', grant_types: ['authorization_code', 'refresh_token'] } });
    expect(clientResponse.status()).toBe(201);
    const client = await clientResponse.json();
    const verifier = randomBytes(32).toString('base64url');
    const query = new URLSearchParams({ client_id: client.client_id, response_type: 'code', redirect_uri: 'https://connector.example/callback', resource: origin + '/mcp', scope: 'messages:read messages:write', state: randomUUID(), code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256' });
    await page.goto('/settings/devices');
    const signedOut = page.waitForResponse(response => response.url().endsWith('/web/v1/logout') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    expect((await signedOut).status()).toBe(200);
    await expect(page.getByRole('heading', { name: 'Sign in with a passkey' })).toBeVisible();
    await page.goto('/oauth/authorize?' + query);
    await expect(page).toHaveURL(/\/signin\?return_to=/);
    await page.getByRole('button', { name: 'Sign in with a passkey', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Connect to Bridge' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Research assistant' })).toBeVisible();
    await expect(page.getByText('connector.example', { exact: true })).toBeVisible();
    await expect(page.getByRole('radio', { name: /Approve first/ })).toBeChecked();
    await expect(page.locator('input[type=radio], input[type=checkbox]')).toHaveCount(0);
    const source = page.getByRole('switch', { name: 'Messages', exact: true });
    await expect(source).toBeChecked();
    await source.click();
    await expect(page.getByRole('button', { name: 'Allow connection', exact: true })).toBeDisabled();
    await source.click();
    await page.screenshot({ path: `${evidence}/consent-${info.project.name}.png`, fullPage: true });
    await page.getByRole('radio', { name: /Read only/ }).click();
    await page.route('https://connector.example/callback?*', route => route.fulfill({ contentType: 'text/html', body: '<html><body>Connected</body></html>' }));
    await page.getByRole('button', { name: 'Allow connection', exact: true }).click();
    await expect(page).toHaveURL(/https:\/\/connector.example\/callback\?/);
    const returned = new URL(page.url());
    expect(returned.searchParams.get('state')).toBe(query.get('state'));
    expect(returned.searchParams.get('iss')).toBe(origin);
    const form = { grant_type: 'authorization_code', client_id: client.client_id, code: returned.searchParams.get('code')!, redirect_uri: 'https://connector.example/callback', code_verifier: verifier, resource: origin + '/mcp' };
    const tokenResponse = await request.post('/oauth/token', { form });
    expect(tokenResponse.ok()).toBe(true);
    const token = await tokenResponse.json();
    expect(token.expires_in).toBe(3600);
    const mcp = async (access: string, method: string, params: object) => request.post('/mcp', { headers: { Authorization: 'Bearer ' + access, Accept: 'application/json, text/event-stream' }, data: { jsonrpc: '2.0', id: 1, method, params } });
    const list = await mcp(token.access_token, 'tools/list', {});
    expect(list.status()).toBe(200);
    expect((await list.json()).result.tools.some((tool: { name: string }) => tool.name === 'messages_chats')).toBe(true);
    const read = await mcp(token.access_token, 'tools/call', { name: 'messages_chats', arguments: {} });
    expect(read.status()).toBe(200);
    const result = (await read.json()).result;
    expect(result.isError).not.toBe(true);
    const chatID = result.structuredContent.chats[0].chat.id;
    const chatTitle = result.structuredContent.chats[0].title;
    await page.goto('/settings/agents');
    await expect(page.getByRole('heading', { name: 'Research assistant' })).toBeVisible();
    await expect(page.getByText('Read only · Messages', { exact: true })).toBeVisible();
    await expect(page.getByText(/^Today at /)).toBeVisible();
    await expect(page.locator('.settings-tile')).toHaveCount(6);
    for (const icon of await page.locator('.settings-tile use').all()) { await expect.poll(() => icon.evaluate(element => (element as SVGGraphicsElement).getBBox().width)).toBeGreaterThan(0); }
    await page.getByRole('button', { name: 'Connect an agent', exact: true }).click();
    await expect(page.getByRole('radio', { name: /Approve first/ })).toBeChecked();
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Writing assistant');
    await page.getByRole('button', { name: 'Connect an agent', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Save this token now. It will only be shown once.' })).toBeVisible();
    const agentToken = await page.getByRole('textbox', { name: 'Agent token', exact: true }).inputValue();
    expect(agentToken).toMatch(/^aba-/);
    for (const name of ['Grok', 'Claude Code', 'Codex', 'curl']) { await page.getByRole('button', { name, exact: true }).click(); }
    expect(await page.locator('.snippet').allTextContents()).toEqual(expect.arrayContaining([expect.stringContaining(origin + '/mcp')]));
    await page.getByRole('button', { name: 'Done', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Agent token', exact: true })).toHaveCount(0);
    await page.locator('.settings-layout, .settings-content').evaluateAll(elements => elements.forEach(element => element.scrollTo(0, 0)));
    await page.screenshot({ path: `${evidence}/agents-${info.project.name}.png`, fullPage: true });
    await page.getByRole('link', { name: 'Approvals', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'All caught up' })).toBeVisible();
    const commandID = randomUUID();
    const text = '[ab-test browser] Please send this after my approval.';
    const pending = await request.post('/v1/op/messages.send', { headers: { Authorization: 'Bearer ' + agentToken }, data: { command_id: commandID, args: { chat_id: chatID, text, files: [{ name: 'Draft.txt', data: Buffer.from('[ab-test browser] Attachment preview').toString('base64') }] } } });
    expect(pending.status()).toBe(200);
    expect((await pending.json()).state).toBe('awaiting_approval');
    await expect(page.getByText(text, { exact: true })).toBeVisible();
    await expect(page.getByText('Writing assistant', { exact: true })).toBeVisible();
    await page.locator('.settings-layout, .settings-content').evaluateAll(elements => elements.forEach(element => element.scrollTo(0, 0)));
    await page.screenshot({ path: `${evidence}/approvals-${info.project.name}.png`, fullPage: true });
    await page.getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'All caught up' })).toBeVisible();
    await expect.poll(async () => { const status = await request.post('/v1/op/commands.status', { headers: { Authorization: 'Bearer ' + agentToken }, data: { command_id: commandID } }); return (await status.json()).state; }).toBe('observed');
    await page.getByRole('link', { name: 'Activity', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'messages.send', exact: true })).toBeVisible();
    await expect(page.getByText(text, { exact: true })).toHaveCount(0);
    await expect(page.getByRole('heading', { name: 'messages.chats', exact: true })).toBeVisible();
    await page.getByRole('textbox', { name: 'Filter by operation', exact: true }).fill('messages.send');
    await page.getByRole('button', { name: 'Apply filters' }).click();
    await expect(page.getByRole('heading', { name: 'messages.chats', exact: true })).toHaveCount(0);
    const refreshForm = { grant_type: 'refresh_token', client_id: client.client_id, resource: origin + '/mcp', refresh_token: token.refresh_token };
    const rotatedResponse = await request.post('/oauth/token', { form: refreshForm });
    expect(rotatedResponse.status()).toBe(200);
    const rotated = await rotatedResponse.json();
    expect(rotated.refresh_token).not.toBe(token.refresh_token);
    const reused = await request.post('/oauth/token', { form: refreshForm });
    expect(reused.status()).toBe(400);
    expect((await mcp(rotated.access_token, 'tools/list', {})).status()).toBe(401);
    const agents = await page.request.get('/web/v1/agents').then(response => response.json());
    const writing = agents.agents.find((agent: { name: string }) => agent.name === 'Writing assistant');
    const revoked = await page.request.delete('/web/v1/agents/' + encodeURIComponent(writing.id), { headers: ownerHeaders });
    expect(revoked.ok()).toBe(true);
    expect((await mcp(agentToken, 'tools/list', {})).status()).toBe(401);
});
