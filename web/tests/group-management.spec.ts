import { expect } from '@playwright/test';
import { test } from './list-session';
import { control } from './session';

test('WEB-MSG-DETAILS group commands reconcile captured name and membership before closing', async ({ page }) => {
    const commands: any[] = [];
    page.on('websocket', socket => socket.on('framesent', frame => {
        const value = JSON.parse(String(frame.payload));
        if (value.t === 'cmd') commands.push(value);
    }));
    await page.goto('/messages');
    await page.locator('.conversation-row').filter({ hasText: 'Weekend Crew' }).click();
    await page.getByRole('button', { name: 'Details', exact: true }).click();
    const details = page.locator('.conversation-details');
    await details.getByRole('button', { name: 'Change Group Name', exact: true }).click();
    const rename = details.getByRole('form', { name: 'Change Group Name' });
    await rename.getByLabel('Group name', { exact: true }).fill('   ');
    await expect(rename.getByRole('button', { name: 'Save Name' })).toBeDisabled();
    await rename.getByLabel('Group name', { exact: true }).fill('[ab-test groups] Name');
    await rename.getByLabel('Group name', { exact: true }).press('Enter');
    await expect(details.getByRole('heading', { name: '[ab-test groups] Name', exact: true })).toBeVisible();
    await expect(rename).toHaveCount(0);
    expect(commands[0].op).toBe('messages.rename_group');
    expect(commands[0].expected_version).toBeGreaterThan(0);
    await details.getByRole('button', { name: 'Add Member', exact: true }).click();
    const add = details.getByRole('form', { name: 'Add Member' });
    await add.getByLabel('Email or phone number').fill('photo@example.com');
    await expect(add).toContainText('already in the conversation');
    await expect(add.getByRole('button', { name: 'Add Member', exact: true })).toBeDisabled();
    await add.getByLabel('Email or phone number').fill('member1@example.com');
    await add.getByRole('button', { name: 'Add Member', exact: true }).click();
    await expect(add).toHaveCount(0);
    await expect(details.locator('.details-member')).toHaveCount(5);
    await details.getByRole('button', { name: 'Remove member1@example.com', exact: true }).click();
    const remove = details.getByRole('form', { name: 'Remove Member' });
    await expect(remove).toContainText('changes the group for everyone');
    await remove.getByRole('button', { name: 'Cancel', exact: true }).click();
    expect(commands).toHaveLength(2);
    await details.getByRole('button', { name: 'Remove member1@example.com', exact: true }).click();
    await remove.getByRole('button', { name: 'Remove Member', exact: true }).click();
    await expect(remove).toHaveCount(0);
    await expect(details.locator('.details-member')).toHaveCount(4);
    await details.getByRole('button', { name: 'Leave this Conversation', exact: true }).click();
    const leave = details.getByRole('form', { name: 'Leave this Conversation' });
    await leave.getByRole('button', { name: 'Leave Conversation', exact: true }).click();
    await expect(leave).toHaveCount(0);
    await expect(details.getByRole('button', { name: 'Leave this Conversation', exact: true })).toHaveCount(0);
    expect(commands.map(value => value.op)).toEqual(['messages.rename_group', 'messages.add_member', 'messages.remove_member', 'messages.leave_group']);
});

test('WEB-MSG-DETAILS uncertain group changes stay locked and Check never redispatches', async ({ page, request }) => {
    let mutations = 0;
    page.on('websocket', socket => socket.on('framesent', frame => { if (JSON.parse(String(frame.payload)).t === 'cmd') mutations++; }));
    await page.goto('/messages');
    await page.locator('.conversation-row').filter({ hasText: 'Weekend Crew' }).click();
    await page.getByRole('button', { name: 'Details', exact: true }).click();
    const details = page.locator('.conversation-details');
    await details.getByRole('button', { name: 'Change Group Name', exact: true }).click();
    const form = details.getByRole('form', { name: 'Change Group Name' });
    await form.getByLabel('Group name', { exact: true }).fill('[ab-test groups] Uncertain');
    await control(request, '/message-fault?name=ui-interference');
    await form.getByRole('button', { name: 'Save Name' }).click();
    await expect(form.getByRole('status')).toContainText('Not sure');
    await expect(form.getByRole('button', { name: 'Save Name' })).toBeDisabled();
    await expect(form.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled();
    await form.getByRole('button', { name: 'Check Change' }).click();
    await expect(form.getByRole('status')).toContainText('Not sure');
    expect(mutations).toBe(1);
    await expect(details.getByRole('heading', { name: 'Weekend Crew', exact: true })).toBeVisible();
});

test('WEB-MSG-DETAILS revoking group proof prevents submission and direct chats hide management', async ({ page, request }) => {
    await page.goto('/messages');
    await page.locator('.conversation-row').filter({ hasText: 'Weekend Crew' }).click();
    await page.getByRole('button', { name: 'Details', exact: true }).click();
    const details = page.locator('.conversation-details');
    await details.getByRole('button', { name: 'Change Group Name', exact: true }).click();
    await control(request, '/capability-unproven');
    const form = details.getByRole('form', { name: 'Change Group Name' });
    await expect(form.getByRole('button', { name: 'Save Name' })).toBeDisabled();
    await expect(form).toContainText('no longer available');
    await form.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(details.getByRole('button', { name: /Add Member|Change Group Name|Remove |Leave this/ })).toHaveCount(0);
    await control(request, '/capability-proven');
    await page.goto('/messages');
    await page.locator('.conversation-row').filter({ hasText: 'Sam Rivera' }).click();
    await page.getByRole('button', { name: 'Details', exact: true }).click();
    await expect(details.getByRole('button', { name: /Add Member|Change Group Name|Remove |Leave this/ })).toHaveCount(0);
});
