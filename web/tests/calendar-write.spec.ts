import { test, expect } from '@playwright/test';
import { bootstrap, control } from './session';
test.use({ timezoneId: 'America/Los_Angeles', locale: 'en-US' });
test('WEB-CAL-WRITE trusted create, edit, alerts, floating dates and delete', async ({ page, context, request }) => {
  await bootstrap(context, request);
  const commands: any[] = [];
  page.on('websocket', socket => socket.on('framesent', event => { const frame = JSON.parse(String(event.payload)); if (frame.t === 'cmd') commands.push(frame); }));
  await page.goto('/calendar/day/2026-10-20');
  await page.getByRole('button', { name: 'New calendar', exact: true }).click();
  let editor = page.getByRole('dialog', { name: 'New calendar', exact: true });
  await editor.getByLabel('Title', { exact: true }).fill('Bridge Test [ab-test] Web Calendar');
  await editor.getByRole('button', { name: 'Create calendar', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Bridge Test [ab-test] Web Calendar', exact: true })).toBeVisible();
  await page.getByLabel('Quick event', { exact: true }).fill('[ab-test] Lunch Friday 1pm');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'New event', exact: true });
  await expect(editor.getByLabel('Title', { exact: true })).toHaveValue('[ab-test] Lunch');
  await expect(editor.getByLabel('Starts', { exact: true })).toHaveValue('2026-10-23T13:00');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'New event', exact: true }).click();
  await editor.getByRole('combobox', { name: 'Calendar', exact: true }).selectOption({ label: 'Bridge Test [ab-test] Web Calendar' });
  await editor.getByLabel('Title', { exact: true }).fill('[ab-test] Written from Calendar');
  await editor.getByLabel('Starts', { exact: true }).fill('2026-10-20T09:00');
  await editor.getByLabel('Ends', { exact: true }).fill('2026-10-20T10:00');
  await editor.getByLabel('Time zone', { exact: true }).fill('America/Los_Angeles');
  await editor.getByLabel('Location', { exact: true }).fill('Corner café');
  await editor.getByRole('button', { name: 'Add alert', exact: true }).click();
  await editor.getByLabel('Minutes before alert 1', { exact: true }).fill('17');
  const save = editor.getByRole('button', { name: 'Save event', exact: true });
  await save.evaluate(element => element.dispatchEvent(new MouseEvent('click', { bubbles: true })));
  await editor.getByLabel('Title', { exact: true }).evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })));
  expect(commands).toHaveLength(1);
  await save.click();
  const created = page.locator('.calendar-event').filter({ hasText: '[ab-test] Written from Calendar' });
  await expect(created).toHaveCount(1); await expect(created).toBeEnabled();
  expect(commands[1].args).toMatchObject({ start: '2026-10-20T16:00:00.000Z', end: '2026-10-20T17:00:00.000Z', alarms: [{ relative_offset: -1020 }] });
  await created.click();
  await page.getByRole('button', { name: 'Edit event', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'Edit event', exact: true });
  await editor.getByLabel('Title', { exact: true }).fill('[ab-test] Floating date');
  await editor.getByLabel('All-day', { exact: true }).check();
  await editor.getByLabel('Starts', { exact: true }).fill('2026-10-20');
  await editor.getByLabel('Ends', { exact: true }).fill('2026-10-21');
  await editor.getByRole('button', { name: 'Save event', exact: true }).click();
  const floating = page.getByRole('button', { name: '[ab-test] Floating date', exact: true });
  await expect(floating).toBeEnabled(); await floating.click();
  await expect(page.getByRole('dialog', { name: 'Event details' })).toContainText('October 21, 2026');
  expect(commands[2].expected_version).toBeGreaterThan(0);
  expect(commands[2].args).toMatchObject({ all_day: true, start: '2026-10-20', end: '2026-10-22' });
  expect(commands[2].args.alarms).toBeUndefined();
  await page.getByRole('button', { name: 'Delete event', exact: true }).click();
  await page.getByRole('dialog', { name: 'Delete event', exact: true }).getByRole('button', { name: 'Delete event', exact: true }).click();
  await expect(floating).toHaveCount(0);
  expect(commands.map(command => command.op)).toEqual(['calendar.create_calendar', 'calendar.create_event', 'calendar.update_event', 'calendar.delete_event']);
});
