import {test,expect} from '@playwright/test';
import {control} from './session';
test('WEB-MSG-REACT first transcript paint defers the picker and attachment queue until use',async({page,context,request})=>{
    const cookie=(await control(request,'/session')).cookie;
    const chat=(await control(request,'/demo-fixtures'))['message-chat'];
    await page.goto(new URL(cookie.url).origin);
    await expect(page.getByRole('heading',{name:'Sign in with a passkey',exact:true})).toBeVisible();
    await context.addCookies([cookie]);
    const requested:string[]=[];
    page.on('request',request=>requested.push(new URL(request.url()).pathname));
    await page.goto('/messages/'+encodeURIComponent(chat));
    const bubble=page.locator('.messages-transcript .bubble[data-part]').last();
    await expect(bubble).toBeVisible();
    await expect(page.getByRole('textbox',{name:'Message',exact:true})).toBeVisible();
    expect(requested.filter(path=>/\/(MessageActions|AttachmentQueue|emoji|CanvasEffectsLayer|CardVideo|ViewerSession|History)-/.test(path))).toEqual([]);
    await bubble.click({button:'right'});
    const picker=page.getByRole('dialog',{name:'Message actions',exact:true});
    await expect(picker).toBeVisible();
    await expect(picker.getByRole('button',{name:'Love',exact:true})).toBeVisible();
    expect(requested.some(path=>/\/MessageActions-/.test(path))).toBe(true);
    await picker.getByRole('button',{name:'More reactions',exact:true}).click();
    await picker.getByRole('searchbox',{name:'Search reactions',exact:true}).fill('party popper');
    await expect(picker.getByRole('button',{name:'Party popper',exact:true})).toBeVisible();
    expect(requested.some(path=>/\/emoji-[^/]+\.json$/.test(path))).toBe(true);
    await picker.getByRole('button',{name:'Close',exact:true}).click();
    await expect(picker).toHaveCount(0);
    await page.getByLabel('Choose attachments', {exact:true}).setInputFiles({name:'[ab-test] lazy.txt',mimeType:'text/plain',buffer:Buffer.from('[ab-test] lazy attachment')});
    await expect(page.getByRole('list',{name:'Attachments',exact:true})).toBeVisible();
    expect(requested.some(path=>/\/AttachmentQueue-/.test(path))).toBe(true);
});
