import { test, expect } from '@playwright/test';
import { prepareListSession as bootstrap } from './list-session';
import { notesFixture } from './notes-fixtures';
import { showNotesFolders, showNotesList } from './notes-navigation';
test('WEB-NOTE-WRITE trusted saves, exact versions, conflict drafts, create and delete', async ({ page, context, request }) => {
    await bootstrap(context, request); const fixture = await notesFixture(page); await page.goto('/notes/folder/fld_test');
    await page.locator('[data-note-id="nte_plain"]').click();
    const editor = page.getByRole('textbox', { name: 'Note text', exact: true });
    await expect(editor).toHaveValue('[ab-test] Plain\nA quiet draft');
    await editor.fill('[ab-test] Saved\nFirst edit');
    await page.evaluate(() => document.querySelector('textarea')!.dispatchEvent(new KeyboardEvent('keyup', { key: 'a', bubbles: true })));
    expect(fixture.commands).toHaveLength(0);
    await editor.press('ArrowRight');
    await expect.poll(() => fixture.commands.length).toBe(1);
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible();
    expect(fixture.commands[0]).toMatchObject({ op: 'notes.update', expected_version: 1, args: { id: 'nte_plain', mode: 'replace', plain_text: '[ab-test] Saved\nFirst edit' } });
    await editor.fill('[ab-test] Saved twice'); await editor.press('ControlOrMeta+s');
    await expect.poll(() => fixture.commands.length).toBe(2);
    expect(fixture.commands[1].expected_version).toBe(2);
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible();
    await showNotesList(page);
    await page.getByRole('button', { name: 'New Note', exact: true }).click();
    await page.getByRole('textbox', { name: 'New note text' }).fill('\nBody');
    await expect(page.getByRole('button', { name: 'Create', exact: true })).toBeDisabled();
    await page.getByRole('textbox', { name: 'New note text' }).fill('[ab-test] New\nBody \n');
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    await expect(page).toHaveURL(/\/notes\/nte_created$/);
    await expect(editor).toHaveValue('[ab-test] New\nBody \n');
    await page.getByRole('button', { name: 'Delete note', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    expect(fixture.commands).toHaveLength(3);
    await page.getByRole('button', { name: 'Delete note', exact: true }).click();
    await page.getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(page.locator('[data-note-id="nte_created"]')).toHaveCount(0);
    expect(fixture.commands[3]).toMatchObject({ op: 'notes.delete', expected_version: 1 });
    await showNotesList(page);
    if (await page.getByRole('button', { name: 'Show folders' }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: 'Show folders' }).click();
    await page.getByRole('button', { name: '+ New Folder', exact: true }).click();
    await page.getByRole('textbox', { name: 'Folder name' }).fill('[ab-test] Folder');
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    await expect(page).toHaveURL(/\/notes\/folder\/fld_created$/);
    await page.goto('/notes/folder/fld_test');
    await page.locator('[data-note-id="nte_plain"]').click();
    await expect(editor).toBeVisible(); fixture.conflict();
    await editor.fill('[ab-test] Keep my draft'); await editor.press('ControlOrMeta+s');
    await expect(page.getByRole('alert')).toContainText('Changed elsewhere');
    await expect(editor).toHaveValue('[ab-test] Keep my draft');
    const count = fixture.commands.length;
    await editor.press('ArrowRight'); await page.getByRole('button', { name: 'Done', exact: true }).click();
    expect(fixture.commands).toHaveLength(count);
    await showNotesFolders(page);
    await page.locator('.app-menu-control').click();
    await page.locator('.app-menu').getByRole('button', { name: 'Reminders', exact: true }).click();
    await expect(page).toHaveURL(/\/reminders$/);
    await expect(page.locator('.reminders-app')).toBeVisible();
    expect(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; })).toBe(true);
    await page.locator('.app-menu-control').click();
    await page.locator('.app-menu').getByRole('button', { name: 'Notes', exact: true }).click();
    await page.locator('[data-note-id="nte_plain"]').click();
    await expect(editor).toHaveValue('[ab-test] Keep my draft');
    await expect(page.getByRole('alert')).toContainText('Changed elsewhere');
    expect(fixture.commands).toHaveLength(count);
    await page.getByRole('button', { name: 'Reload note', exact: true }).click();
    await expect(editor).toHaveValue('[ab-test] External change');
});
test('WEB-NOTE-WRITE dirty drafts save before folder navigation and warn on unload', async ({ page, context, request }) => {
    await bootstrap(context, request); const fixture = await notesFixture(page); await page.goto('/notes/nte_plain');
    const editor = page.getByRole('textbox', { name: 'Note text', exact: true }); await expect(editor).toBeVisible();
    await editor.fill('[ab-test] Navigation save');
    const prevented = await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; });
    expect(prevented).toBe(true); expect(fixture.commands).toHaveLength(0);
    await showNotesList(page);
    if (await page.getByRole('button', { name: 'Show folders' }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: 'Show folders' }).click();
    await page.getByRole('button', { name: /^Nested/ }).click();
    await expect.poll(() => fixture.commands.length).toBe(1);
    expect(fixture.commands[0].args.plain_text).toBe('[ab-test] Navigation save');
    await page.goto('/notes/nte_plain'); await expect(editor).toBeVisible();
    await editor.fill('[ab-test] Escape save'); await editor.press('Escape');
    await expect.poll(() => fixture.commands.length).toBe(2);
    expect(fixture.commands[1]).toMatchObject({ op: 'notes.update', expected_version: 2, args: { plain_text: '[ab-test] Escape save' } });
    await expect(page).toHaveURL(/\/notes$/);
});
test('WEB-NOTE-WRITE keyup throttle never sends from timers and external changes retain the draft', async ({ page, context, request }) => {
    await bootstrap(context, request); const fixture = await notesFixture(page); await page.clock.install(); await page.goto('/notes/nte_plain');
    const editor = page.getByRole('textbox', { name: 'Note text', exact: true }); await expect(editor).toBeVisible();
    await editor.fill('[ab-test] First'); await editor.press('ArrowRight');
    await expect.poll(() => fixture.commands.length).toBe(1);
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible();
    await editor.fill('[ab-test] Throttled'); await editor.press('ArrowRight');
    expect(fixture.commands).toHaveLength(1);
    await page.clock.runFor(900); expect(fixture.commands).toHaveLength(1);
    await editor.press('ArrowRight'); await expect.poll(() => fixture.commands.length).toBe(2);
    await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible();
    await editor.fill('[ab-test] My local draft'); fixture.external();
    await expect(page.getByRole('alert')).toContainText('Changed elsewhere');
    await expect(editor).toHaveValue('[ab-test] My local draft'); await expect(editor).toBeFocused();
    await editor.press('ControlOrMeta+s'); expect(fixture.commands).toHaveLength(2);
});
