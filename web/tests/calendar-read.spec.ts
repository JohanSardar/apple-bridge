import { test, expect } from '@playwright/test';
import { bootstrap } from './session';

test.use({ timezoneId: 'America/Los_Angeles' });

test('WEB-CAL-READ all views, civil dates, inspector, filters, search and history', async ({ page, context, request }, info) => {
  await bootstrap(context, request);
  await page.goto('/calendar/month/2026-10-20');
  await expect(page.getByRole('main', { name: 'Calendar', exact: true })).toBeVisible();
  await expect(page.getByRole('grid', { name: 'October 2026' })).toBeVisible();
  await expect(page.getByRole('gridcell')).toHaveCount(42);
  await expect(page.locator('[data-event-id]').first()).toBeAttached();
  if (info.project.name.endsWith('phone')) await expect(page.getByRole('region', { name: 'Selected day events' })).toContainText('Project check-in');
  await page.screenshot({ path: `../lab/evidence/private/web/calendar-month-${info.project.name}.png` });
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Project check-in', exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Project check-in', exact: true }).first().click();
  const inspector = page.getByRole('dialog', { name: 'Event details' });
  await expect(inspector).toBeVisible();
  await expect(inspector).toContainText('Review the draft');
  await expect(inspector).toContainText('America/New_York');
  await expect(inspector).toContainText('10 minutes before');
  await expect(inspector.getByRole('link', { name: 'Get directions' })).toHaveAttribute('href', /maps\.apple\.com/);
  await expect(inspector.getByText('Travel time', { exact: true })).toHaveCount(0);
  const eventPath = new URL(page.url()).pathname;
  await page.reload();
  await expect(inspector).toContainText('Project check-in');
  await expect(page).toHaveURL(new RegExp(eventPath));
  await page.getByRole('button', { name: 'Close event details' }).click();
  await page.goto('/calendar/day/2026-10-20');
  await expect(page.locator('.calendar-time-day')).toHaveCount(1);
  const originalHeight = await page.locator('.calendar-time-day').evaluate(element => element.getBoundingClientRect().height);
  await page.locator('.calendar-hours').hover();
  await page.keyboard.down('Control');
  await page.mouse.wheel(0, -160);
  await page.keyboard.up('Control');
  await expect.poll(() => page.locator('.calendar-time-day').evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThan(originalHeight);
  await expect(page.locator('.calendar-time-event').filter({ hasText: 'Project check-in' })).toBeVisible();
  await page.getByRole('button', { name: 'Week', exact: true }).click();
  await expect(page.locator('.calendar-time-day')).toHaveCount(7);
  await expect(page.locator('.calendar-time-event').first()).toBeAttached();
  await page.screenshot({ path: `../lab/evidence/private/web/calendar-week-${info.project.name}.png` });
  await page.getByRole('button', { name: 'Year', exact: true }).click();
  await expect(page.locator('.year-mini')).toHaveCount(12);
  await page.getByRole('button', { name: 'Month', exact: true }).click();
  await page.getByRole('button', { name: 'Next period' }).click();
  await expect(page.getByRole('grid', { name: 'November 2026' })).toBeVisible();
  await page.getByRole('button', { name: 'Previous period' }).click();
  await expect(page.getByRole('grid', { name: 'October 2026' })).toBeVisible();
  if (await page.getByRole('button', { name: 'Show calendars' }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: 'Show calendars' }).click();
  const work = page.getByRole('checkbox', { name: 'Work', exact: true });
  await work.uncheck();
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Project check-in', exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Show calendars' })).toBeVisible();
  if (await page.getByRole('button', { name: 'Show calendars' }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: 'Show calendars' }).click();
  await expect(work).not.toBeChecked();
  await work.check();
  await page.getByRole('searchbox', { name: 'Search events' }).fill('Corner café');
  if (await page.getByRole('button', { name: 'Close calendars' }).isVisible()) await page.getByRole('button', { name: 'Close calendars' }).click();
  await expect(page.getByRole('heading', { name: 'Search results' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Lunch with Sam', exact: true }).first()).toBeVisible();
  await expect(page.getByRole('button', { name: 'Project check-in', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.goto('/calendar/day/2026-10-24');
  await expect(page.locator('.calendar-all-day')).toContainText('Weekend away');
  await page.locator('.calendar-all-day').getByRole('button', { name: 'Weekend away', exact: true }).click();
  await expect(inspector).toContainText('October 26, 2026');
  await page.getByRole('button', { name: 'Close event details' }).click();
  await page.goto('/calendar/day/2026-10-27');
  await expect(page.locator('.calendar-all-day')).not.toContainText('Weekend away');
  await page.locator('.calendar-content').focus();
  await page.keyboard.press('ArrowRight');
  await expect(page).toHaveURL(/2026-10-28$/);
  await page.keyboard.press('ControlOrMeta+3');
  await expect(page.getByRole('grid', { name: 'October 2026' })).toBeVisible();
  await page.keyboard.press('ControlOrMeta+ArrowRight');
  await expect(page).toHaveURL(/2026-11-01$/);
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', await page.locator('body').evaluate(element => element.clientWidth));
  await bootstrap(context, request, 'public');
  await page.reload();
  await expect(page.getByRole('main', { name: 'Calendar', exact: true })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('ab.appearance'))).toBeNull();
});
