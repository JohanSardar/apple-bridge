import { test, expect } from '@playwright/test';
import { bootstrap, control } from './session';
test.use({ timezoneId: 'America/New_York', locale: 'en-US', reducedMotion: 'no-preference' });
test('WEB-REM-WRITE trusted create, edit, completion, move, delete and create list', async ({ page, context, request }) => {
  await bootstrap(context, request);
  const commands: any[] = [];
  page.on('websocket', socket => socket.on('framesent', event => { const value = JSON.parse(String(event.payload)); if (value.t === 'cmd') commands.push(value); }));
  await page.goto('/reminders');
  await page.getByRole('button', { name: 'Travel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Travel', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New Reminder', exact: true }).click();
  const title = page.getByRole('textbox', { name: 'Reminder title', exact: true });
  await title.fill('[ab-test] Buy milk tomorrow');
  const tomorrow = await page.evaluate(() => { const date = new Date(); date.setDate(date.getDate() + 1); return [date.getFullYear(), String(date.getMonth() + 1).padStart(2, '0'), String(date.getDate()).padStart(2, '0')].join('-'); });
  await expect(page.getByLabel('Reminder date', { exact: true })).toHaveValue(tomorrow);
  await page.getByRole('button', { name: 'Add Reminder', exact: true }).evaluate(element => element.dispatchEvent(new MouseEvent('click', { bubbles: true })));
  await title.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })));
  expect(commands).toHaveLength(0);
  const add = page.getByRole('button', { name: 'Add Reminder', exact: true });
  expect(await add.evaluate(element => { const values = getComputedStyle(element), luminance = (color: string) => { const parts = color.match(/[\d.]+/gu)!.slice(0, 3).map(value => { const n = Number(value) / 255; return n <= .04045 ? n / 12.92 : ((n + .055) / 1.055) ** 2.4; }); return parts[0] * .2126 + parts[1] * .7152 + parts[2] * .0722; }, a = luminance(values.color), b = luminance(values.backgroundColor); return (Math.max(a, b) + .05) / (Math.min(a, b) + .05); })).toBeGreaterThanOrEqual(4.5);
  await add.click();
  const created = page.locator('.reminder-row').filter({ hasText: '[ab-test] Buy milk' });
  await expect(created).toHaveCount(1);
  await expect(created).not.toHaveAttribute('data-pending', 'true');
  expect(commands.filter(value => value.op === 'reminders.create')).toHaveLength(1);
  expect(commands[0].args).toMatchObject({ title: '[ab-test] Buy milk', due: tomorrow, due_all_day: true });
  await created.getByRole('button', { name: 'Edit [ab-test] Buy milk', exact: true }).click();
  await page.getByRole('textbox', { name: 'Reminder title', exact: true }).fill('[ab-test] Milk and bread');
  await page.getByRole('textbox', { name: 'Reminder notes', exact: true }).fill('[ab-test] Written from the web');
  await page.getByLabel('Reminder date', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Save Reminder', exact: true }).click();
  await expect(page.locator('.reminder-title').filter({ hasText: '[ab-test] Milk and bread' })).toHaveCount(1);
  const edited = page.locator('.reminder-row').filter({ hasText: '[ab-test] Milk and bread' });
  await expect(edited.locator('time')).toHaveCount(0);
  const complete = edited.getByRole('button', { name: 'Complete [ab-test] Milk and bread', exact: true });
  const target = await complete.boundingBox(); expect(target!.width).toBeGreaterThanOrEqual(44); expect(target!.height).toBeGreaterThanOrEqual(44);
  await complete.click();
  await expect(edited).toHaveClass(/reminder-completing/);
  await expect(edited).toHaveCount(0);
  await page.getByLabel('Show Completed', { exact: true }).check();
  await expect(edited).toHaveClass(/reminder-completed/);
  await expect(edited.locator('.reminder-title')).toHaveCSS('text-decoration-line', 'none');
  await edited.getByRole('button', { name: 'Reopen [ab-test] Milk and bread', exact: true }).click();
  await expect(edited).not.toHaveClass(/reminder-completed/);
  await edited.getByRole('button', { name: 'Details for [ab-test] Milk and bread', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Reminder', exact: true }).click();
  await page.getByLabel('Reminder list', { exact: true }).selectOption({ label: 'Personal' });
  await page.getByRole('button', { name: 'Save Reminder', exact: true }).click();
  if (await page.getByRole('button', { name: 'Close details', exact: true }).isVisible()) await page.getByRole('button', { name: 'Close details', exact: true }).click();
  await expect(edited).toHaveCount(0);
  if (await page.getByRole('button', { name: 'Back to lists' }).isVisible()) await page.getByRole('button', { name: 'Back to lists' }).click();
  await page.getByRole('button', { name: 'Personal', exact: true }).click();
  await edited.getByRole('button', { name: 'Details for [ab-test] Milk and bread', exact: true }).click();
  await page.getByRole('button', { name: 'Delete Reminder', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm Delete', exact: true }).click();
  await expect(edited).toHaveCount(0);
  if (await page.getByRole('button', { name: 'Back to lists' }).isVisible()) await page.getByRole('button', { name: 'Back to lists' }).click();
  await page.getByRole('button', { name: 'Add List', exact: true }).click();
  await page.getByRole('textbox', { name: 'List name', exact: true }).fill('Bridge Test [ab-test] Web list');
  await page.getByRole('button', { name: 'Create List', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Bridge Test [ab-test] Web list', exact: true })).toBeVisible();
  expect(commands.map(value => value.op)).toEqual(['reminders.create', 'reminders.update', 'reminders.complete', 'reminders.uncomplete', 'reminders.update', 'reminders.delete', 'reminders.create_list']);
  expect(commands.filter(value => !['reminders.create', 'reminders.create_list'].includes(value.op)).every(value => value.expected_version > 0)).toBe(true);
});

