import { test, expect } from '@playwright/test';
import { bootstrap } from './session';
test('WEB-HANDLES-ROUTE frame batches resolve contact names and guard session, origin and limits',async({page,context,request})=>{
    const headers={Origin:process.env.AB_WEB_URL!};
    expect((await page.request.post('/web/v1/handles',{headers,data:{ids:[]}})).status()).toBe(401);
    await bootstrap(context,request);
    const fixtureResponse=await request.post(process.env.AB_WEB_CONTROL!+'/handles-fixture',{headers:{'X-Bridge-Lab':process.env.AB_WEB_CONTROL_KEY!}});
    expect(fixtureResponse.ok(),await fixtureResponse.text()).toBe(true);
    const fixture=await fixtureResponse.json();
    const response=await page.request.post('/web/v1/handles',{headers,data:{ids:fixture.ids}});
    expect(response.status()).toBe(200);
    const result=await response.json();
    expect(result.handles).toHaveLength(2);
    expect(result.handles[0]).toMatchObject({handle_id:fixture.ids[0],display_name:'Sam Rivera',given_name:'Sam',family_name:'Rivera',initials:'SR',contact_id:fixture.avatar.record,avatar:{digest:fixture.avatar.digest}});
    expect(result.handles[1]).toMatchObject({handle_id:fixture.ids[1],display_name:'plain@example.com',service:'SMS'});
    const duplicate=await page.request.post('/web/v1/handles',{headers,data:{ids:Array(500).fill(fixture.ids[0])}});
    expect(duplicate.status()).toBe(200);
    expect((await duplicate.json()).handles).toHaveLength(1);
    const unknown=await page.request.post('/web/v1/handles',{headers,data:{ids:['missing-handle']}});
    expect(unknown.status()).toBe(200);
    expect((await unknown.json()).handles).toEqual([]);
    expect((await page.request.post('/web/v1/handles',{headers,data:{ids:['']}})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers,data:{ids:Array(501).fill(fixture.ids[0])}})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers,data:{ids:['x'.repeat(70000)]}})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers,data:'{'})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers,data:'{"ids":[]} {}'})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers,data:'{"ids":[]}'+ ' '.repeat(70000)})).status()).toBe(400);
    expect((await page.request.post('/web/v1/handles',{headers:{Origin:'https://bridge.invalid'},data:{ids:fixture.ids}})).status()).toBe(403);
});
